// Generates src/design-system/styles/utilities.css from the token scales (skill
// frontend-architecture § 4, spec 076): spacing from --sy-space-*, tones and surfaces from the role
// tokens. Every value is a var() of a token, so a rebrand changes tokens.css, never this file.
// `node scripts/gen-utilities.mjs` writes it; `--check` exits 1 when the file is out of date
// (tests/utilities.test.ts runs the same comparison).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** @param {string} p */
const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const TOKENS = here('../src/design-system/assets/css/tokens.css');
const OUT = here('../src/design-system/styles/utilities.css');

/** Spacing utilities: class stem → the properties it sets. */
const SPACING = {
  m: ['margin'], mt: ['margin-top'], mr: ['margin-right'], mb: ['margin-bottom'], ml: ['margin-left'],
  mx: ['margin-left', 'margin-right'], my: ['margin-top', 'margin-bottom'],
  p: ['padding'], pt: ['padding-top'], pr: ['padding-right'], pb: ['padding-bottom'], pl: ['padding-left'],
  px: ['padding-left', 'padding-right'], py: ['padding-top', 'padding-bottom'],
  gap: ['gap'],
};

/** Text tones and surfaces: utility → the role token (never the raw palette). */
const TONES = {
  'text-default': '--sy-text', 'text-muted': '--sy-text-muted', 'text-intent': '--sy-intent',
  'text-ok': '--sy-ok', 'text-active': '--sy-active', 'text-tobe': '--sy-tobe', 'text-fail': '--sy-fail',
};
const SURFACES = {
  'bg-ground': '--sy-bg-ground', 'bg-well': '--sy-bg-well', 'bg-plate': '--sy-bg-plate', 'bg-raised': '--sy-bg-raised',
  'bg-intent-tint': '--sy-intent-tint', 'bg-tobe-tint': '--sy-tobe-tint', 'bg-fail-tint': '--sy-fail-tint',
};
const BORDERS = { 'border-weld': '--sy-border-weld', 'border-plate': '--sy-border-plate', 'border-control': '--sy-border-control' };
const FONT_SIZES = ['xs', 'sm', 'body', 'label', 'mono', 'micro'];

/** Layout utilities: a fixed set, no values of their own. */
const LAYOUT = {
  block: 'display: block', 'inline-block': 'display: inline-block', flex: 'display: flex',
  'inline-flex': 'display: inline-flex', grid: 'display: grid', hidden: 'display: none',
  'flex-col': 'flex-direction: column', wrap: 'flex-wrap: wrap', 'items-start': 'align-items: flex-start',
  'items-center': 'align-items: center', 'items-end': 'align-items: flex-end',
  'justify-start': 'justify-content: flex-start', 'justify-center': 'justify-content: center',
  'justify-end': 'justify-content: flex-end', 'justify-between': 'justify-content: space-between',
  grow: 'flex: 1 1 auto', 'min-w-0': 'min-width: 0', 'w-full': 'width: 100%', mono: 'font-family: var(--sy-font-mono)',
};

/**
 * The custom properties tokens.css defines.
 * @param {string} css
 * @returns {Set<string>}
 */
export function tokenNames(css) {
  return new Set([...css.matchAll(/^\s*(--sy-[a-z0-9-]+)\s*:/gm)].map((m) => m[1] ?? ''));
}

/**
 * @param {Set<string>} names
 * @param {string} token
 */
function need(names, token) {
  if (!names.has(token)) throw new Error(`tokens.css has no ${token}`);
  return `var(${token})`;
}

/**
 * @param {string} tokensCss
 * @returns {string}
 */
export function utilitiesCss(tokensCss) {
  const names = tokenNames(tokensCss);
  const steps = [...names].filter((n) => /^--sy-space-\d+$/.test(n)).map((n) => Number(n.slice(11))).sort((a, b) => a - b);
  const lines = [
    '/* GENERATED by scripts/gen-utilities.mjs from tokens.css: do not edit (spec 076).',
    '   Token utility classes (skill frontend-architecture § 4): spacing, tones, surfaces, borders,',
    '   font sizes and layout. Used inside design-system components and through Box\'s typed props;',
    '   a rebrand changes tokens.css, and this file follows. */',
    '@layer sy.utilities {',
  ];
  for (const [stem, props] of Object.entries(SPACING))
    for (const step of [0, ...steps]) {
      const value = step === 0 ? '0' : need(names, `--sy-space-${step}`);
      lines.push(`  .u-${stem}-${step} { ${props.map((p) => `${p}: ${value};`).join(' ')} }`);
    }
  for (const [name, token] of Object.entries(TONES)) lines.push(`  .u-${name} { color: ${need(names, token)}; }`);
  for (const [name, token] of Object.entries(SURFACES)) lines.push(`  .u-${name} { background: ${need(names, token)}; }`);
  for (const [name, token] of Object.entries(BORDERS))
    lines.push(`  .u-${name} { border: var(--sy-weld) solid ${need(names, token)}; }`);
  for (const size of FONT_SIZES) lines.push(`  .u-fs-${size} { font-size: ${need(names, `--sy-fs-${size}`)}; }`);
  for (const [name, decl] of Object.entries(LAYOUT)) lines.push(`  .u-${name} { ${decl}; }`);
  lines.push('}', '');
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = utilitiesCss(readFileSync(TOKENS, 'utf8'));
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {
      // missing: out of date
    }
    if (current !== css) {
      console.error('utilities.css is out of date: run `pnpm ds:utilities`');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, css);
    console.log(`wrote ${OUT}`);
  }
}
